import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { deriveStage2BRealCalibration, setStage2BCalibrationProfileHash } from "../src/lib/synth-v2/stage2b-validation.ts";
import { STAGE2B_EXECUTION_CODE_PATHS, STAGE2B_FROZEN_INPUT_PATHS } from "../src/lib/synth-v2/stage2b-provenance.ts";
import { parseSourceCsv } from "../src/lib/synth-v2/csv.ts";

const ROOT = process.cwd();
const SYNTH_DIR = join(ROOT, "src/lib/synth-v2");
const SOURCE_PATH = join(ROOT, "XAUUSD_30min_2020-01-24_to_2026-10-01.csv");
const EXPECTED_SOURCE_SHA256 = "cf393fc399ae63b921ce6d5ebc7de05e4cb7481d51079d2d18c164414cfea1d3";
const REAL_BANDS_PATH = join(SYNTH_DIR, "STAGE2B-REAL-BANDS.json");
const CONFIG_PATH = join(SYNTH_DIR, "STAGE2B-CONFIG.json");
const PRE_REGISTRATION_PATH = join(SYNTH_DIR, "STAGE2B-PRE-REGISTRATION.json");

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}
function hashFile(path) {
  return sha256(readFileSync(path));
}
function jsonFile(path, value) {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}
function recordedSpecHash() {
  const line = readFileSync(join(SYNTH_DIR, "SPEC-2b.sha256"), "utf8").trim();
  const match = line.match(/^([a-f0-9]{64})\s+src\/lib\/synth-v2\/SPEC-2b\.md$/);
  if (!match) throw new Error("SPEC-2b.sha256 is malformed");
  const actual = hashFile(join(SYNTH_DIR, "SPEC-2b.md"));
  if (actual !== match[1]) throw new Error(`SPEC-2b hash mismatch: recorded ${match[1]}, actual ${actual}`);
  return actual;
}
function verifySeedList(seeds) {
  const range = (start, count) => Array.from({ length: count }, (_, index) => start + index);
  if (JSON.stringify(seeds.design) !== JSON.stringify(range(5001, 200))) throw new Error("DESIGN seed list differs from the pre-registered range");
  if (JSON.stringify(seeds.lockedTest) !== JSON.stringify(range(6001, 200))) throw new Error("LOCKED TEST seed list differs from the pre-registered range");
  const regimes = ["quiet_range", "normal_chop", "trend_up", "trend_down", "whipsaw", "expansion_up", "expansion_down"];
  if (JSON.stringify(Object.keys(seeds.nullSeedsByRegime)) !== JSON.stringify(regimes)) throw new Error("NULL regime order differs from the pre-registration");
  for (const regime of regimes) {
    if (JSON.stringify(seeds.nullSeedsByRegime[regime]) !== JSON.stringify(range(7001, 100))) throw new Error(`NULL seeds differ for ${regime}`);
  }
  const auditPaths = seeds.rebuildVerification?.paths;
  if (!Array.isArray(auditPaths) || auditPaths.length !== 20 || auditPaths.some((item) => item.set === "LOCKED TEST" || item.set === "LOCKED_TEST")) {
    throw new Error("rebuild verification must pre-list 20 non-LOCKED paths");
  }
  if (new Set(auditPaths.map((item) => `${item.set}|${item.regimeId ?? ""}|${item.seed}`)).size !== 20) {
    throw new Error("rebuild verification paths must be unique");
  }
}

const actualSourceHash = hashFile(SOURCE_PATH);
if (actualSourceHash !== EXPECTED_SOURCE_SHA256) {
  throw new Error(`source SHA-256 mismatch: expected ${EXPECTED_SOURCE_SHA256}, got ${actualSourceHash}; stopping before calibration`);
}
const profilePath = join(SYNTH_DIR, "profile.json");
const profile = JSON.parse(readFileSync(profilePath, "utf8"));
if (profile.sourceSha256 !== EXPECTED_SOURCE_SHA256) throw new Error("Stage 1b profile source hash differs from the frozen CSV");
const specSha256 = recordedSpecHash();
const seeds = JSON.parse(readFileSync(join(SYNTH_DIR, "STAGE2B-SEEDS.json"), "utf8"));
verifySeedList(seeds);

const source = parseSourceCsv(readFileSync(SOURCE_PATH, "utf8"));
let calibration = deriveStage2BRealCalibration(source, profile, specSha256);
calibration = setStage2BCalibrationProfileHash(calibration, hashFile(profilePath));
for (const metric of ["atrPercent", "drift", "varianceRatio8", "varianceRatio16"]) {
  const width = calibration.distributions[metric].p83 - calibration.distributions[metric].p17;
  if (!(width > 0 && Number.isFinite(width))) throw new Error(`real W=20 ${metric} p83-p17 width is not positive`);
}
jsonFile(REAL_BANDS_PATH, calibration);

const config = {
  schemaVersion: 1,
  status: "PRE-REGISTERED; no Stage 2b path data generated by this calibrator",
  sourceFile: "XAUUSD_30min_2020-01-24_to_2026-10-01.csv",
  sourceSha256: actualSourceHash,
  profileSha256: hashFile(profilePath),
  specSha256,
  seedListSha256: hashFile(join(SYNTH_DIR, "STAGE2B-SEEDS.json")),
  realBandsSha256: hashFile(REAL_BANDS_PATH),
  windowWeekdays: 20,
  segments: { minimumWeekdays: 20, maximumWeekdays: 80, distribution: "rounded log-uniform" },
  transitions: { minimumBars: 48, maximumBars: 200 },
  overlays: { probabilityPerSegment: 0.25, minimumWeekdays: 2, maximumWeekdays: 5, outsideBlendZones: true },
  sets: {
    design: { firstSeed: 5001, lastSeed: 5200, paths: 200 },
    lockedTest: { firstSeed: 6001, lastSeed: 6200, paths: 200, analyzed: false },
    null: { firstSeed: 7001, lastSeed: 7100, pathsPerRegime: 100, regimeCount: 7, weekdaysPerPath: 140 },
  },
  statistics: ["atrPercent", "drift", "varianceRatio8", "varianceRatio16"],
  standards: { c1TercileTolerance: 0.15, c2NormalizedTolerance: 0.25, inseparableAucThreshold: 0.6 },
  runtime: { node: process.version, icu: process.versions.icu ?? null, tzdata: process.versions.tz ?? null, tzEnvironment: process.env.TZ ?? null },
};
jsonFile(CONFIG_PATH, config);

const codeHashes = Object.fromEntries(STAGE2B_EXECUTION_CODE_PATHS.map((path) => [path, hashFile(resolve(ROOT, path))]));
const frozenInputHashes = Object.fromEntries(STAGE2B_FROZEN_INPUT_PATHS.map((path) => [path, hashFile(resolve(ROOT, path))]));
const preRegistration = {
  schemaVersion: 1,
  recordedBeforeSyntheticGeneration: true,
  generatedSyntheticPaths: 0,
  specSha256,
  sourceSha256: actualSourceHash,
  profileSha256: hashFile(profilePath),
  seedListSha256: hashFile(join(SYNTH_DIR, "STAGE2B-SEEDS.json")),
  realBandsSha256: hashFile(REAL_BANDS_PATH),
  configSha256: hashFile(CONFIG_PATH),
  codeHashes,
  frozenInputHashes,
};
jsonFile(PRE_REGISTRATION_PATH, preRegistration);
console.log(`Stage 2b pre-registration frozen; no synthetic paths generated. SPEC-2b SHA-256=${specSha256}; real bands SHA-256=${preRegistration.realBandsSha256}.`);
